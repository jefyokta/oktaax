namespace Oktaax\Http;

use Oktaax\Application\ConnectionScope;
use Oktaax\Application\RequestScope;
use Oktaax\Exception\ValidationException;
use Oktaax\Exception\HttpException;
use Oktaax\Validation\Validator;
use Swoole\Http\Request as HttpRequest;
use Stringable;

/**
 * Wrap one native HTTP request with explicit input sources, validation, and separate request/connection cleanup.
 *
 * @property string|null $_token Generated by CSRF middleware when registered.
 */

class Request implements Stringable
{
    /**
     * The current request instance.
     *
     * @var Request
     */

    /**
     * Native connection descriptor when supplied by the runtime.
     *
     * @var int|null
     */

    public $fd = null;
    /**
     * The original native Swoole request.
     *
     * @var \Swoole\Http\Request
     */

    public $request;

    /**
     * Most recent validation failure map, or null before validation.
     *
     * @var array<string, array<string, string>>|null
     */

    public $errors;

    /**
     * Request-local application metadata independent from query/body input.
     *
     * @var array<string, mixed>
     */

    protected $attributes = [];
    /**
     * Matched route parameters; excluded from input() and all().
     *
     * @var array<string, string>
     */
    public array $params = [];

    /**
     * Native request headers indexed by normalized lowercase names.
     *
     * @var array<string, string>|null
     */
    public ?array $headers;

    /**
     * Application-owned helper callables bound by the HTTP kernel.
     *
     * @var array<string, callable>
     */
    private array $helpers = [];

    public ?string $uri;

    private RequestScope $scope;
    private ConnectionScope $connection;
    private ?\Closure $connectionProbe = null;
    private ?Validator $validator = null;

    private bool $jsonParsed = false;
    private mixed $jsonData = null;

    public function __construct(HttpRequest $request)
    {
        $this->request = $request;
        $this->fd = $request->fd ?? null;
        $this->uri = $request->server['request_uri'] ?? '/';
        $this->headers = $request->header;
        $this->scope = new RequestScope();
        $this->connection = new ConnectionScope();
    }
    public function scope(): RequestScope
    {
        return $this->scope;
    }
    public function connection(): ConnectionScope
    {
        return $this->connection;
    }
    /**
     * Register temporary request resources for guaranteed reverse-order cleanup.
     *
     * @param \Closure(): mixed $callback
     */
    public function defer(\Closure $callback): void
    {
        $this->scope->defer($callback);
    }
    public function useValidator(Validator $validator): void
    {
        $this->validator = $validator;
    }
    /**
     * Bind the owning application helper map for this request.
     *
     * @param array<string, callable> $helpers
     * @internal
     */
    public function useHelpers(array $helpers): void
    {
        $this->helpers = $helpers;
    }
    /**
     * Bind a native writability probe used by connection polling.
     *
     * @param \Closure(): bool $probe
     * @internal
     */
    public function watchConnection(\Closure $probe): void
    {
        $this->connectionProbe = $probe;
    }
    /**
     * Observe detected client disconnection, rather than ordinary successful response completion.
     *
     * @param callable(\Oktaax\Event\Event<array{aborted: bool, disconnected: bool}>): mixed $callback
     */
    public function onClientDisconnected(callable $callback): void
    {
        $this->connection->onDisconnect($callback);
    }
    /**
     *
     * @param string $name
     * @return mixed
     */

    public function __get($name)
    {
        if (property_exists($this->request, $name)) {
            return $this->request->$name;
        }
        return $this->attributes[$name] ?? null;
    }

    /**
     * Observe response/connection closure; interval=true additionally polls native writability.
     *
     * @param callable(\Oktaax\Event\Event<array{aborted: bool, disconnected: bool}>): mixed $callback
     */
    public function onClose(callable $callback, ?bool $interval = false)
    {
        $this->connection->onClose($callback);
        if ($interval && $this->connectionProbe !== null) {
            $this->connection->watch($this->connectionProbe);
        }
    }

    public function close($aborted = false, bool $disconnected = false)
    {
        $this->connection->close($aborted, $disconnected);
    }

    /**
     *
     * @param string $name
     * @param mixed $value
     */
    public function __set($name, $value)
    {
        $this->attributes[$name] = $value;
    }

    /**
     *
     * @param string $name
     * @param mixed $value
     */

    public function setHeader($name, $value)
    {
        $this->headers[strtolower($name)] = $value;
    }

    /**
     *
     * @param string $name
     * @return bool
     */
    public function __isset($name)
    {
        return isset($this->request->$name) || isset($this->attributes[$name]);
    }

    /**
     *
     * @param string $name
     */
    public function __unset($name)
    {
        unset($this->attributes[$name]);
    }

    /**
     * Forward native request methods or an application helper with the supplied arguments.
     *
     * @param string $name
     * @param array<array-key, mixed> $arguments
     * @return mixed
     * @throws \BadMethodCallException When neither method nor helper exists.
     */
    public function __call($name, $arguments)
    {
        if (method_exists($this->request, $name)) {
            return \call_user_func_array([$this->request, $name], $arguments);
        }

        if ($injected = $this->helpers[$name] ?? null) {
            return \call_user_func($injected, ...$arguments);
        }

        throw new \BadMethodCallException("Method {$name} does not exist.");
    }
    /**
     * Read query, body, then cookies; a present null wins and defaults apply only to missing keys.
     *
     * @return mixed
     */
    public function input(string $key, mixed $default = null)
    {
        if (array_key_exists($key, $this->request->get ?? [])) {
            return $this->request->get[$key];
        }
        $body = $this->bodies();
        if (array_key_exists($key, $body)) {
            return $body[$key];
        }
        if (array_key_exists($key, $this->request->cookie ?? [])) {
            return $this->request->cookie[$key];
        }

        return $default;
    }
    /**
     * Read a native form field; unlike body(), this accessor does not decode JSON.
     *
     * @return mixed
     */
    public function post(string $key, mixed $default = null)
    {
        return $this->request->post[$key] ?? $default;
    }

    /**
     * Merge query, decoded body fields, and cookies; earlier sources win and present null values are preserved.
     *
     * @return array<array-key, mixed>
     */
    public function all(): array
    {
        return ($this->request->get ?? []) +
            $this->bodies() +
            ($this->request->cookie ?? []);
    }

    /**
     * Check if the request has a given parameter.
     *
     * @param string $key
     * @return bool
     */
    public function has(string $key): bool
    {
        return array_key_exists($key, $this->request->get ?? []) ||
            array_key_exists($key, $this->bodies()) ||
            array_key_exists($key, $this->request->cookie ?? []);
    }

    /**
     * Read one header case-insensitively.
     *
     * @param string $key
     * @return string|null
     */
    public function header($key)
    {
        $key = strtolower($key);
        return $this->headers[$key] ?? null;
    }

    /**
     * Check if the request query has a given parameter.
     *
     * @param string $key
     * @return bool
     */
    public function queryHas(string $key)
    {
        return isset($this->request->get[$key]);
    }

    /**
     * Get the client's user agent.
     *
     * @return string|null
     */
    public function userAgent()
    {
        return $this->request->header['user-agent'] ?? null;
    }

    /**
     * Determine if the request is a JSON request.
     *
     * @return bool
     */
    public function isJson(): bool
    {
        $type = strtolower(
            trim(explode(';', $this->header('content-type') ?? '')[0]),
        );
        return $type === 'application/json' || str_ends_with($type, '+json');
    }

    /**
     * Determine if the request is a form submission.
     *
     * @return bool
     */
    public function isFormSubmission()
    {
        return $this->isMethod('POST') &&
            str_contains(
                strtolower($this->header('content-type') ?? ''),
                'application/x-www-form-urlencoded',
            );
    }

    /**
     * Get the path of the request URI.
     *
     * @return string
     */
    public function path(): string
    {
        return parse_url(
            $this->request->server['request_uri'] ?? '',
            PHP_URL_PATH,
        ) ?:
            '/';
    }

    /**
     * Determine if the request is requesting JSON.
     *
     * @return bool
     */
    public function wantsJson()
    {
        return str_contains(
            strtolower($this->header('accept') ?? ''),
            'application/json',
        );
    }

    /**
     * Determine if the request is requesting JavaScript.
     *
     * @return bool
     */

    public function wantsJS()
    {
        return str_contains(
            strtolower($this->header('accept') ?? ''),
            'application/javascript',
        );
    }

    public function protocol()
    {
        return !empty($this->request->server['https']) &&
            $this->request->server['https'] !== 'off'
            ? 'https'
            : 'http';
    }
    /**
     * Get the host from the request.
     *
     * @return string
     */
    public function host()
    {
        return $this->headers['host'] ?? '';
    }
    /**
     * Compare param with request method
     *
     * @return bool
     */
    public function isMethod(string $method): bool
    {
        return strtoupper($method) === $this->getMethod();
    }

    public function getMethod(): string
    {
        return strtoupper(
            $this->request->server['request_method'] ??
            $this->request->getMethod() ?:
            'GET',
        );
    }

    /**
     * Validate the payload field map and return only input keys named in the rules.
     *
     * @param array<string, string|list<string>> $rules
     * @param array<array-key, mixed>|null $data
     * @return array<array-key, mixed>
     * @throws \Oktaax\Exception\ValidationException When one or more validation rules fail.
     * @throws \Oktaax\Exception\HttpException When the HTTP body is not a field map.
     */
    public function validate(array $rules, array|null $data = null)
    {
        if (null === $data) {
            $data = $this->body() ?? [];
        }
        if (!is_array($data)) {
            throw new HttpException(
                400,
                'Request body must be an object or array.',
            );
        }

        $this->errors = ($this->validator ??= new Validator())->validate(
            $data,
            $rules,
        );

        $reqValidated = new RequestValidated(
            array_intersect_key($data, $rules),
            !empty($this->errors) ? $this->errors : null,
        );
        if (!$reqValidated->isOk()) {
            throw new ValidationException($reqValidated->getErrors());
        }

        return $reqValidated->getData();
    }

    /**
     * Read JSON according to Content-Type, otherwise native form fields; no key returns the entire body.
     *
     * @throws \Oktaax\Exception\HttpException When JSON decoding fails.
     */
    public function body(?string $key = null, mixed $default = null): mixed
    {
        $data = $this->isJson() ? $this->json() : $this->request->post ?? [];
        if ($key === null) {
            return $data;
        }
        return is_array($data) && array_key_exists($key, $data)
            ? $data[$key]
            : $default;
    }

    /**
     * Decode the complete raw body once, preserving JSON scalars/null; no key returns the entire value.
     *
     * @throws \Oktaax\Exception\HttpException When JSON decoding fails.
     */
    public function json(?string $key = null, mixed $default = null): mixed
    {
        if (!$this->jsonParsed) {
            $raw = $this->request->rawContent();
            try {
                $this->jsonData =
                    $raw === false || $raw === ''
                        ? null
                        : json_decode($raw, true, 512, JSON_THROW_ON_ERROR);
            } catch (\JsonException $e) {
                throw new HttpException(400, 'Malformed JSON request body.');
            }
            $this->jsonParsed = true;
        }
        if ($key === null) {
            return $this->jsonData;
        }
        return is_array($this->jsonData) &&
            array_key_exists($key, $this->jsonData)
            ? $this->jsonData[$key]
            : $default;
    }
    /**
     * Read a native request cookie, or null when absent.
     *
     * @param string $name
     * @return string|null
     */

    public function cookie($name)
    {
        return $this->request->cookie[$name] ?? null;
    }
    public function hasHeader($key)
    {
        return isset($this->headers[strtolower($key)]);
    }
    public function isInertia()
    {
        return $this->hasHeader('x-inertia');
    }

    public function isAjax()
    {
        return $this->header('x-requested-with') === 'XMLHttpRequest';
    }

    public function xhr()
    {
        return $this->isAjax();
    }

    public function __invoke($key)
    {
        return $this->input($key);
    }

    /**
     * Return body fields as a map, or an empty map for a scalar body.
     *
     * @return array<array-key, mixed>
     */
    public function bodies()
    {
        $body = $this->body();
        return is_array($body) ? $body : [];
    }

    /**
     * Merge route parameters, query values, and body fields with first-source precedence.
     *
     * @return array<array-key, mixed>
     */
    public function parameters()
    {
        return $this->params + ($this->request->get ?? []) + $this->bodies();
    }

    public function __toString(): string
    {
        return json_encode($this);
    }

    public function get($key, $default = null)
    {
        return $this->query($key, $default);
    }

    /**
     * Read query fields; a present null value does not fall back to the default.
     *
     * @return ($key is null ? array<array-key, mixed> : mixed)
     */
    public function query(?string $key = null, mixed $default = null): mixed
    {
        $data = $this->request->get ?? [];
        return $key === null
            ? $data
            : (array_key_exists($key, $data)
                ? $data[$key]
                : $default);
    }

    public function param(string $key, mixed $default = null): mixed
    {
        return array_key_exists($key, $this->params)
            ? $this->params[$key]
            : $default;
    }
}
